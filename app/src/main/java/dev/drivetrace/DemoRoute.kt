            val lat = Math.toRadians(c - a); val lon = Math.toRadians(d - b)
            val h = sin(lat / 2).pow(2) + cos(Math.toRadians(a)) * cos(Math.toRadians(c)) * sin(lon / 2).pow(2)
            this[i] = this[i - 1] + 6371 * 2 * atan2(sqrt(h), sqrt(1 - h))
        }
    }
    val lengthKm: Double get() = distances.last()
    fun at(distanceKm: Double): Pair<Double, Double> {
        val d = ((distanceKm % lengthKm) + lengthKm) % lengthKm
        val end = distances.binarySearch(d).let { if (it >= 0) it else -it - 1 }.coerceIn(1, points.lastIndex)
        val start = end - 1
        val fraction = (d - distances[start]) / (distances[end] - distances[start]).coerceAtLeast(0.0000001)
        return (points[start].first + (points[end].first - points[start].first) * fraction) to
            (points[start].second + (points[end].second - points[start].second) * fraction)
    }
    /** Includes every road vertex between samples, including across the loop seam. */
    fun path(fromKm: Double, toKm: Double): List<Pair<Double, Double>> {
        require(toKm >= fromKm)
        val result = mutableListOf(at(fromKm))
        val startLap = floor(fromKm / lengthKm).toInt()
        val endLap = floor(toKm / lengthKm).toInt()
        for(lap in startLap..endLap) {
            for(i in points.indices) {
                val d = lap * lengthKm + distances[i]
                if(d > fromKm && d < toKm) result += points[i]
            }
        }
        result += at(toKm)
        return result
    }

